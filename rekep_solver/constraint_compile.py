# constraint_compiler.py
# ------------------------------------------------------------
# Writes LLM-produced constraint code to constraints.py and hot-loads it.
# Updated flow:
#   1) cc = ConstraintCompiler(out_dir)
#   2) cc.bind_dependencies(np=np, _pos_cost=..., _parallel_cost=..., ...)
#   3) parts = cc.extract(llm_output)  # dict: grasp_stage/grasp_keypoints/macros/helper_funcs/constraints
#   4) cc.write_to_py(parts)           # compose & write constraints.py
#   5) loaded = cc.load_py()           # returns {
#                                      #   "grasp_stage": [...],
#                                      #   "grasp_keypoints": [...],
#                                      #   "constraints": {stage: [callables...]}
#                                      # }
#
# Convenience:
#   - cc.list_stage_constraints(stage) -> names
#   - cc.evaluate_stage(stage, keypoints) -> EvalResult
#
# No external deps beyond stdlib.
# ------------------------------------------------------------

from __future__ import annotations

import importlib.util
import importlib
import os
import re
import sys
from .episode_constraints import bind_episode_constraints
import types
from pathlib import Path
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple, Callable, Union

_HEADER_BANNER = "# === Auto-Generated by ConstraintCompiler ===\n"
_SECTION_MACROS = "# ---------------- Macros (Injected) ----------------\n"
_SECTION_HELPERS = "# --------------- Helper Functions (Injected) ---------------\n"
_SECTION_CONSTRAINTS = "# --------------- Constraints (Injected) ---------------\n"
_SECTION_FOOTER = "# --------------- Footer (Do not edit) ---------------\n"

ConstraintCallable = Callable[[Any], float]

_PY_PREAMBLE = (
    "from __future__ import annotations\n"
    "import math\n"
    "import numpy as np  # required for macros like np.array(...)\n"
    "# The following symbols may be overwritten by bind_dependencies(...):\n"
    "_compose_vector = globals().get('_compose_vector')\n"
    "_compose_unit_vector = globals().get('_compose_unit_vector')\n"
    "_compose_plane_normal = globals().get('_compose_plane_normal')\n"
    "_unit = globals().get('_unit')\n"
    "_pos_cost = globals().get('_pos_cost')\n"
    "_parallel_cost = globals().get('_parallel_cost')\n"
    "_orthogonal_cost = globals().get('_orthogonal_cost')\n"
    "_theta_cost = globals().get('_theta_cost')\n"
    "_point_in_plane_xy_cost = globals().get('_point_in_plane_xy_cost')\n"
    "_point_in_plane_yz_cost = globals().get('_point_in_plane_yz_cost')\n"
    "_point_in_plane_xz_cost = globals().get('_point_in_plane_xz_cost')\n"
    "_point_in_aabb_cost = globals().get('_point_in_aabb_cost')\n"
    "_angle_30deg_from_neg_z_cost = globals().get('_angle_30deg_from_neg_z_cost')\n"
    "_angle_60deg_from_neg_z_cost = globals().get('_angle_60deg_from_neg_z_cost')\n"
    "\n"
)

@dataclass
class EvalResult:
    stage: int
    constraint_names: List[str]
    constraint_costs: List[float]
    total_cost: float


class ConstraintCompiler:
    """
    Typical flow:
      1) Instantiate with an output directory.
      2) bind_dependencies(...) to inject runtime functions/objects (np, cost fns, etc.)
      3) Extract the llm_output via extract(llm_output) -> {
            "grasp_stage": str | list[int] | None,
            "grasp_keypoints": str | list[int] | None,
            "macros": str,
            "helper_funcs": str,
            "constraints": str,
         }
      4) write_to_py(parts) to compose final constraints.py
      5) load_py(): import the module, inject deps, and return:
            {
              "grasp_stage": list[int] | None,
              "grasp_keypoints": list[int] | None,
              "constraints": { stage:int -> list[callable] }
            }

    Notes:
      - Constraint functions are named stage{N}_constraint{K}.
      - Stages with grasp or release (1/-1) do not need constraints.
      - Module name is made unique from out_dir to avoid collisions.
    """

    def __init__(self, module_dir: str, module_name: str = "constraints.py"):
        os.makedirs(module_dir, exist_ok=True)

        self.module_dir = module_dir
        self.module_path = os.path.join(module_dir, module_name)

        safe_suffix = re.sub(r"[^a-zA-Z0-9_]", "_", self.module_dir)
        self.safe_module_name = f"_constraints_{safe_suffix}"
        self.module: Optional[types.ModuleType] = None
        self._bound_deps: Dict[str, Any] = {}

    # -------------------- Public API --------------------

    def bind_dependencies(self, **deps: Any) -> None:
        """Store runtime deps to inject after module load (np, cost fns, etc.)."""
        self._bound_deps.update(deps)
        if self.module is not None:
            for k, v in deps.items():
                setattr(self.module, k, v)

    def extract(self, llm_output: Union[str, Dict[str, Any]]) -> Dict[str, Any]:
        """
        Extract {grasp_stage, grasp_keypoints, macros, helper_funcs, constraints} from LLM output.

        Accepts:
          - dict already containing the keys (passes through, with light normalization)
          - raw Python string (attempts to parse)

        Heuristics for string parsing:
          - grasp_stage: first assignment like `grasp_stage = [...]`
          - grasp_keypoints: first assignment like `grasp_keypoints = [...]`
          - constraints: functions named `def stage<digits>_constraint<digits>(...)`
          - helper_funcs: other def blocks not matching constraint name
          - macros: top-of-file global assignments / constants (best-effort)
        """
        if isinstance(llm_output, dict):
            return {
                "grasp_stage": llm_output.get("grasp_stage"),
                "grasp_keypoints": llm_output.get("grasp_keypoints"),
                "macros": llm_output.get("macros", "") or "",
                "helper_funcs": llm_output.get("helper_funcs", "") or "",
                "constraints": llm_output.get("constraints", "") or "",
            }

        code = self._strip_triple_fence(str(llm_output))

        # 1) grasp_stage / grasp_keypoints (as literal text snippet)
        grasp_stage_text = self._extract_grasp_stage_text(code)
        grasp_keypoints_text = self._extract_grasp_keypoints_text(code)

        # 2) Collect all def blocks
        def_blocks = self._extract_def_blocks(code)

        # Split def blocks into constraints vs helpers
        constraint_blocks: List[str] = []
        helper_blocks: List[str] = []
        for header, body in def_blocks:
            if re.match(r"^def\s+stage\d+_constraint\d+\s*\(", header):
                constraint_blocks.append(header + body)
            else:
                helper_blocks.append(header + body)

        constraints_src = "\n\n".join(constraint_blocks).strip()
        helper_src = "\n\n".join(helper_blocks).strip()

        # 3) Macros (best-effort): gather top-level assignments/constants that are not inside def blocks.
        macros_src = self._extract_macros_best_effort(code, def_blocks, grasp_stage_text)

        return {
            "grasp_stage": grasp_stage_text,           # string assignment or None
            "grasp_keypoints": grasp_keypoints_text,   # string assignment or None
            "macros": macros_src,
            "helper_funcs": helper_src,
            "constraints": constraints_src,
        }

    def write_to_py(self, parts: Dict[str, Any], encoding: str = "utf-8") -> None:
        """
        Compose constraints.py from extracted parts.
        - If parts['grasp_stage'] is a list, serialize it; if it's assignment text, write as is.
        - Same for grasp_keypoints.
        """
        grasp_stage_section = self._normalize_grasp_stage(parts.get("grasp_stage"))
        grasp_keypoints_section = self._normalize_grasp_keypoints(parts.get("grasp_keypoints"))

        macros = parts.get("macros", "") or ""
        helpers = parts.get("helper_funcs", "") or ""
        constraints = parts.get("constraints", "") or ""

        content_parts = [
            _HEADER_BANNER,
            _PY_PREAMBLE,                # <- add this line
            grasp_stage_section,
            grasp_keypoints_section,
            _SECTION_MACROS,
            self._ensure_ends_with_newline(macros),
            _SECTION_HELPERS,
            self._ensure_ends_with_newline(helpers),
            _SECTION_CONSTRAINTS,
            self._ensure_ends_with_newline(constraints),
            _SECTION_FOOTER,
            "## End of auto-generated file.\n",
        ]
        final_src = "\n".join(content_parts)

        with open(self.module_path, "w", encoding=encoding) as f:
            f.write(final_src)

    def load_py(self, episode_context=None) -> Dict[str, Any]:
        """
        Import (or reload) the generated constraints.py and inject dependencies.
        Returns a dict:
            {
              "grasp_stage": list[int] | None,
              "grasp_keypoints": list[int] | None,
              "constraints": { stage:int -> list[callable] }
            }
        """
        self._import_or_reload()
        if self._bound_deps:
            for k, v in self._bound_deps.items():
                setattr(self.module, k, v)

        grasp = self.get_grasp_stage()
        gk = self.get_grasp_keypoints()

        self.bound_module = bind_episode_constraints(self.module, episode_context)
        # Build constraints map: stage -> list of callables
        constraints_map: Dict[int, List[ConstraintCallable]] = {}
        for name in dir(self.bound_module):
            if not re.match(r"^stage(\d+)_constraint\d+$", name):
                continue
            fn = getattr(self.bound_module, name)
            if not callable(fn):
                continue
            stage_idx = int(re.findall(r"^stage(\d+)_constraint", name)[0])
            constraints_map.setdefault(stage_idx, []).append(fn)

        # Sort each stage's constraint functions by trailing numeric suffix
        for stage, fns in constraints_map.items():
            fns.sort(key=lambda f: self._trailing_int(getattr(f, "__name__", "")))

        return {"grasp_stage": grasp, "grasp_keypoints": gk, "constraints": constraints_map}

    # --- Introspection / Convenience ---

    def get_grasp_stage(self) -> Optional[List[int]]:
        self._ensure_loaded()
        val = getattr(self.module, "grasp_stage", None)
        if isinstance(val, (list, tuple)):
            return list(val)
        return None

    def get_grasp_keypoints(self) -> Optional[List[int]]:
        """Return list of ints if present; else None."""
        self._ensure_loaded()
        val = getattr(self.module, "grasp_keypoints", None)
        if isinstance(val, (list, tuple)):
            return list(map(int, val))
        return None

    def list_stage_constraints(self, stage: int) -> List[str]:
        self._ensure_loaded()
        prefix = f"stage{stage}_constraint"
        names = [
            n for n in dir(self.module)
            if n.startswith(prefix) and callable(getattr(self.module, n))
        ]
        names.sort(key=self._trailing_int)
        return names

    def evaluate_stage(self, stage: int, keypoints) -> EvalResult:
        self._ensure_loaded()
        fn_names = self.list_stage_constraints(stage)
        if not fn_names:
            raise RuntimeError(f"No constraint functions found for stage {stage}.")
        costs: List[float] = []
        for name in fn_names:
            fn = getattr(self.bound_module, name)
            try:
                val = fn(keypoints)
            except Exception as e:
                raise RuntimeError(f"Error calling {name}(keypoints): {e}") from e
            try:
                costs.append(float(val))
            except Exception:
                raise TypeError(f"{name} returned non-scalar {val!r}.")
        return EvalResult(stage=stage, constraint_names=fn_names, constraint_costs=costs, total_cost=float(sum(costs)))

    # -------------------- Internals --------------------

    def _ensure_loaded(self) -> None:
        if self.module is None:
            raise RuntimeError("Constraints module is not loaded. Call load_py() after write_to_py().")

    def _import_or_reload(self) -> None:
        if self.safe_module_name in sys.modules:
            del sys.modules[self.safe_module_name]
        spec = importlib.util.spec_from_file_location(self.safe_module_name, self.module_path)
        if spec is None or spec.loader is None:
            raise ImportError(f"Could not create spec for {self.module_path}")
        module = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(module)  # type: ignore[attr-defined]
        except Exception as e:
            raise ImportError(f"Failed to import generated constraints module: {e}") from e
        sys.modules[self.safe_module_name] = module
        self.module = module

    @staticmethod
    def _strip_triple_fence(s: str) -> str:
        s = s.strip()
        if s.startswith("```"):
            s = re.sub(r"^```[a-zA-Z0-9_-]*\n?", "", s)
        if s.endswith("```"):
            s = re.sub(r"\n?```$", "", s)
        return s

    @staticmethod
    def _ensure_ends_with_newline(s: str) -> str:
        return s if s.endswith("\n") else (s + "\n")

    @staticmethod
    def _trailing_int(name: str) -> int:
        m = re.search(r"(\d+)$", name or "")
        return int(m.group(1)) if m else 10**9

    @staticmethod
    def _extract_grasp_stage_text(code: str) -> Optional[str]:
        # Grab the FIRST occurrence; allow whitespace/comments on the line.
        m = re.search(r"^\s*grasp_stage\s*=\s*(\[.*?\])\s*$", code, re.MULTILINE | re.DOTALL)
        if not m:
            return None
        # Preserve assignment form: "grasp_stage = [...]" for direct injection
        line = m.group(0).strip()
        return line

    @staticmethod
    def _extract_grasp_keypoints_text(code: str) -> Optional[str]:
        """
        Grab the FIRST occurrence like:
            grasp_keypoints = [...]
        and return the whole assignment line (preserved), else None.
        """
        m = re.search(r"^\s*grasp_keypoints\s*=\s*(\[.*?\])\s*$",
                      code, re.MULTILINE | re.DOTALL)
        if not m:
            return None
        return m.group(0).strip()

    @staticmethod
    def _extract_def_blocks(code: str) -> List[Tuple[str, str]]:
        """
        Return list of (def_line, body_text) for top-level def blocks (best-effort).
        We're not doing a full parser; this is robust enough for typical LLM output.
        """
        it = list(re.finditer(r"(?m)^(def\s+[a-zA-Z_]\w*\s*\([^)]*\)\s*:\s*)", code))
        blocks: List[Tuple[str, str]] = []
        if not it:
            return blocks
        for i, m in enumerate(it):
            start = m.start(1)
            end = it[i + 1].start(1) if i + 1 < len(it) else len(code)
            chunk = code[start:end]
            nl = chunk.find("\n")
            if nl < 0:
                header = chunk.strip()
                body = ""
            else:
                header = chunk[:nl].strip()
                body = chunk[nl:].rstrip()
            blocks.append((header, body))
        return blocks

    @staticmethod
    def _extract_macros_best_effort(code: str, def_blocks: List[Tuple[str, str]], grasp_stage_text: Optional[str]) -> str:
        """
        Pull likely macros (top-level assignments/constants) from before the first def.
        Also include any non-def, non-empty lines that look like indices/aliases.
        """
        first_def_pos = min((code.find(h) for h, _ in def_blocks if code.find(h) != -1), default=len(code))
        head = code[:first_def_pos]

        lines = []
        for line in head.splitlines():
            s = line.strip()
            if not s:
                continue
            if (grasp_stage_text and s.startswith("grasp_stage")) or s.startswith("grasp_keypoints"):
                # Skip: we write grasp_stage/grasp_keypoints separately at the top
                continue
            # Keep comment lines, consts, index aliases, enums, etc.
            # Heuristic: allow assignments (A = ...), constants, comments.
            if re.match(r"^[A-Za-z_][A-Za-z0-9_]*\s*=", s) or s.startswith("#"):
                lines.append(line)
        return "\n".join(lines).strip()

    @staticmethod
    def _normalize_grasp_stage(gs: Any) -> str:
        """
        Accept:
          - None: returns comment placeholder
          - list/tuple of ints: serialize as Python
          - str: if contains 'grasp_stage', emit as-is; if it's just '[...]', wrap in assignment
        """
        if gs is None:
            return "# (No grasp_stage provided)\n"
        if isinstance(gs, (list, tuple)):
            return f"grasp_stage = {list(map(int, gs))}\nnum_stages = len(grasp_stage)\n"
        if isinstance(gs, str):
            s = gs.strip()
            if s.startswith("grasp_stage"):
                # Ensure num_stages exists as convenience
                if "num_stages" not in s:
                    s += "\nnum_stages = len(grasp_stage)"
                return s + "\n"
            # If it's just the list literal
            if s.startswith("[") and s.endswith("]"):
                return f"grasp_stage = {s}\nnum_stages = len(grasp_stage)\n"
            # Fallback: emit as a comment to avoid syntax errors
            return f"# Unrecognized grasp_stage format from LLM:\n# {s}\n"
        # Fallback
        return "# (Unrecognized grasp_stage type)\n"

    @staticmethod
    def _normalize_grasp_keypoints(gk: Any) -> str:
        """
        Accept:
          - None: emit comment
          - list/tuple of ints: serialize as Python
          - str: if contains 'grasp_keypoints', emit as-is; if '[...]', wrap in assignment
        """
        if gk is None:
            return "# (No grasp_keypoints provided)\n"
        if isinstance(gk, (list, tuple)):
            return f"grasp_keypoints = {list(map(int, gk))}\n"
        if isinstance(gk, str):
            s = gk.strip()
            if s.startswith("grasp_keypoints"):
                return s + "\n"
            if s.startswith("[") and s.endswith("]"):
                return f"grasp_keypoints = {s}\n"
            return f"# Unrecognized grasp_keypoints format from LLM:\n# {s}\n"
        return "# (Unrecognized grasp_keypoints type)\n"


